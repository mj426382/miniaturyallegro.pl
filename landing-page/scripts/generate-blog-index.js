/**
 * Builds src/data/blogIndex.ts – post METADATA only (no content) – from src/data/blogPosts/*.ts.
 *
 * The listing pages (Home, /blog) only need titles/excerpts, so shipping every article body in
 * the main bundle (≈0.5 MB) made each page load slower. Article bodies are now loaded lazily
 * per slug (see src/data/blogLoader.ts). Run automatically by `npm run dev` / `npm run build`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const postsDir = resolve(__dirname, '../src/data/blogPosts')
const outFile = resolve(__dirname, '../src/data/blogIndex.ts')

function field(src, name) {
  const sq = src.match(new RegExp(`(?:^|[\\s,{])${name}:\\s*'((?:[^'\\\\]|\\\\.)*)'`, 'm'))
  if (sq) return sq[1].replace(/\\'/g, "'").replace(/\\\\/g, '\\')
  const dq = src.match(new RegExp(`(?:^|[\\s,{])${name}:\\s*"((?:[^"\\\\]|\\\\.)*)"`, 'm'))
  if (dq) return dq[1].replace(/\\"/g, '"').replace(/\\\\/g, '\\')
  return null
}

const posts = readdirSync(postsDir)
  .filter((f) => f.endsWith('.ts'))
  .map((f) => {
    const src = readFileSync(resolve(postsDir, f), 'utf-8')
    const slug = field(src, 'slug') ?? f.replace(/\.ts$/, '')
    return {
      id: field(src, 'id') ?? slug,
      slug,
      title: field(src, 'title') ?? slug,
      excerpt: field(src, 'excerpt') ?? '',
      publishedAt: field(src, 'publishedAt') ?? '1970-01-01',
      modifiedAt: field(src, 'modifiedAt') ?? undefined,
      author: field(src, 'author') ?? undefined,
      readTime: Number(src.match(/readTime:\s*(\d+)/)?.[1] ?? 5),
      category: field(src, 'category') ?? 'Poradniki',
    }
  })
  .sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : a.publishedAt > b.publishedAt ? -1 : 0))

const content = `// GENERATED by scripts/generate-blog-index.js – do not edit by hand.
// Metadata of every post (no bodies). Bodies load lazily via src/data/blogLoader.ts.
export interface BlogPostMeta {
  id: string
  slug: string
  title: string
  excerpt: string
  publishedAt: string
  modifiedAt?: string
  author?: string
  readTime: number
  category: string
}

export const blogIndex: BlogPostMeta[] = ${JSON.stringify(posts, null, 2)}
`
writeFileSync(outFile, content, 'utf-8')
console.log(`✅ blogIndex.ts generated (${posts.length} posts, metadata only)`)
