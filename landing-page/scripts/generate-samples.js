/**
 * Builds src/data/samples.ts from real before/after pairs dropped into public/samples/.
 *
 * Naming: <name>-before.(jpg|png|webp) + <name>-after.(jpg|png|webp)
 * Optional captions: public/samples/captions.json  { "<name>": { "title": "...", "style": "Białe tło" } }
 *
 * The landing page shows the "Przed / po" section only when at least one pair exists,
 * so nothing fabricated is ever displayed. Run automatically by `npm run build`.
 *
 * Spec 17, AC-PERF-008: the cards are 260–380 CSS px wide, so every photo also gets 400 px and 700 px WebP
 * variants in public/samples/w400/ and w700/ (rebuilt when missing or older than the photo) for `srcset`.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'fs'
import sharp from 'sharp'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const samplesDir = resolve(__dirname, '../public/samples')
const outFile = resolve(__dirname, '../src/data/samples.ts')

const IMAGE_RE = /^(.+)-(before|after)\.(jpe?g|png|webp)$/i
const VARIANT_WIDTHS = [400, 700]

/** `srcset` for one photo: the smaller variants (created on demand) plus the original at its own width. */
async function srcSet(file) {
  const source = resolve(samplesDir, file)
  const { width } = await sharp(source).metadata()
  const base = file.replace(/\.[^.]+$/, '.webp')
  const candidates = []
  for (const w of VARIANT_WIDTHS.filter((w) => w < width)) {
    const dir = resolve(samplesDir, `w${w}`)
    const target = resolve(dir, base)
    if (!existsSync(target) || statSync(target).mtimeMs < statSync(source).mtimeMs) {
      mkdirSync(dir, { recursive: true })
      await sharp(source).resize({ width: w }).webp({ quality: 80, effort: 6 }).toFile(target)
    }
    candidates.push(`/samples/w${w}/${base} ${w}w`)
  }
  return [...candidates, `/samples/${file} ${width}w`].join(', ')
}

let pairs = []
if (existsSync(samplesDir)) {
  const files = readdirSync(samplesDir)
  const byName = new Map()
  for (const file of files) {
    const m = file.match(IMAGE_RE)
    if (!m) continue
    const [, name, kind] = m
    const entry = byName.get(name) ?? {}
    entry[kind.toLowerCase()] = file
    byName.set(name, entry)
  }
  let captions = {}
  const captionsFile = resolve(samplesDir, 'captions.json')
  if (existsSync(captionsFile)) {
    try {
      captions = JSON.parse(readFileSync(captionsFile, 'utf-8'))
    } catch (err) {
      console.warn('⚠️  captions.json is not valid JSON – ignoring', err.message)
    }
  }
  const complete = [...byName.entries()].filter(([, e]) => e.before && e.after).sort(([a], [b]) => a.localeCompare(b))
  for (const [name, e] of complete) {
    pairs.push({
      id: name,
      before: `/samples/${e.before}`,
      after: `/samples/${e.after}`,
      beforeSrcSet: await srcSet(e.before),
      afterSrcSet: await srcSet(e.after),
      title: captions[name]?.title ?? name.replace(/[-_]+/g, ' '),
      style: captions[name]?.style ?? null,
    })
  }
}

const content = `// GENERATED by scripts/generate-samples.js – do not edit by hand.
// Drop <name>-before.jpg / <name>-after.jpg into public/samples/ and rebuild.
export interface SamplePair {
  id: string
  before: string
  after: string
  beforeSrcSet: string
  afterSrcSet: string
  title: string
  style: string | null
}

export const samplePairs: SamplePair[] = ${JSON.stringify(pairs, null, 2)}
`
writeFileSync(outFile, content, 'utf-8')
console.log(`✅ samples.ts generated (${pairs.length} before/after pairs)`)
