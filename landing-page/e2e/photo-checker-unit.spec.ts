const solid = (width: number, height: number, channels: 3 | 4, background: sharp.Color) => sharp({ create: { width, height, channels, background } })
const u8 = (b: Buffer) => new Uint8Array(b.buffer, b.byteOffset, b.byteLength)
const analyze = (b: Buffer | Uint8Array, name = 'test') => analyzeBytes(b instanceof Uint8Array ? b : u8(b), name, b.length)

function box(type: string, payload: number[]): number[] {
  const size = 8 + payload.length
  return [(size >>> 24) & 255, (size >>> 16) & 255, (size >>> 8) & 255, size & 255, ...[...type].map((c) => c.charCodeAt(0)), ...payload]
}
const be32 = (n: number) => [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255]
const ascii = (s: string) => [...s].map((c) => c.charCodeAt(0))

/** Minimal HEIF structure: ftyp heic + meta with a thumbnail ispe, the primary ispe and an irot. */
function heic(width: number, height: number, irot = 0): Uint8Array {
  const ftyp = box('ftyp', [...ascii('heic'), 0, 0, 0, 0, ...ascii('mif1'), ...ascii('heic')])
  const thumb = box('ispe', [0, 0, 0, 0, ...be32(320), ...be32(240)])
  const ispe = box('ispe', [0, 0, 0, 0, ...be32(width), ...be32(height)])
  const rot = irot ? box('irot', [irot]) : []
  const meta = box('meta', [0, 0, 0, 0, ...box('iprp', box('ipco', [...thumb, ...ispe, ...rot]))])
  return new Uint8Array([...ftyp, ...meta])
}

/** PNG signature + IHDR only – a header of a huge image without its pixels. */
function pngHeader(width: number, height: number, colorType = 2): Uint8Array {
  return new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, ...box('IHDR', [...be32(width), ...be32(height), 8, colorType, 0, 0, 0]), 0, 0, 0, 0])
}

function bmp(width: number, height: number): Uint8Array {
  const b = Buffer.alloc(54)
  b.write('BM', 0, 'ascii')
  b.writeUInt32LE(54, 2)
  b.writeUInt32LE(40, 14)
  b.writeInt32LE(width, 18)
  b.writeInt32LE(height, 22)
  b.writeUInt16LE(1, 26)
  b.writeUInt16LE(24, 28)
  return u8(b)
}

test.describe('[AC-TOOL-001] format, dimensions, ratio, orientation, size and alpha', () => {
  test('[AC-TOOL-001] JPEG, PNG, WebP, AVIF, GIF and TIFF generated by sharp', async () => {
    const cases: Array<{ name: string; buf: Buffer; format: string; w: number; h: number; alpha: boolean | null }> = [
      { name: 'jpeg', buf: await solid(1600, 1200, 3, '#ffffff').jpeg().toBuffer(), format: 'jpeg', w: 1600, h: 1200, alpha: false },
      { name: 'png rgb', buf: await solid(800, 600, 3, '#336699').png().toBuffer(), format: 'png', w: 800, h: 600, alpha: false },
      { name: 'png rgba', buf: await solid(800, 800, 4, { r: 0, g: 0, b: 0, alpha: 0 }).png().toBuffer(), format: 'png', w: 800, h: 800, alpha: true },
      { name: 'png palette + tRNS', buf: await solid(64, 32, 4, { r: 255, g: 0, b: 0, alpha: 0.5 }).png({ palette: true }).toBuffer(), format: 'png', w: 64, h: 32, alpha: true },
      { name: 'webp lossy', buf: await solid(1000, 750, 3, '#ffffff').webp({ quality: 80 }).toBuffer(), format: 'webp', w: 1000, h: 750, alpha: false },
      { name: 'webp lossless', buf: await solid(501, 333, 3, '#123456').webp({ lossless: true }).toBuffer(), format: 'webp', w: 501, h: 333, alpha: false },
      { name: 'webp alpha', buf: await solid(640, 480, 4, { r: 0, g: 0, b: 0, alpha: 0 }).webp({ quality: 80 }).toBuffer(), format: 'webp', w: 640, h: 480, alpha: true },
      { name: 'avif', buf: await solid(1200, 800, 3, '#ffffff').avif({ quality: 50 }).toBuffer(), format: 'avif', w: 1200, h: 800, alpha: false },
      { name: 'gif', buf: await solid(300, 200, 3, '#ff0000').gif().toBuffer(), format: 'gif', w: 300, h: 200, alpha: null },
      { name: 'tiff', buf: await solid(700, 500, 3, '#00ff00').tiff().toBuffer(), format: 'tiff', w: 700, h: 500, alpha: null },
    ]
    for (const c of cases) {
      const a = analyze(c.buf, c.name)
      expect(a.error, c.name).toBeNull()
      expect(a.format, c.name).toBe(c.format)
      expect([a.width, a.height], c.name).toEqual([c.w, c.h])
      expect(a.hasAlphaChannel, c.name).toBe(c.alpha)
      expect(a.bytes, c.name).toBe(c.buf.length)
      expect(a.megapixels, c.name).toBeCloseTo((c.w * c.h) / 1e6, 6)
    }
  })

  test('[AC-TOOL-001] EXIF orientation 6 swaps the displayed sides of a JPEG', async () => {
    const buf = await solid(1600, 1200, 3, '#ffffff').jpeg().withMetadata({ orientation: 6 }).toBuffer()
    const a = analyze(buf)
    expect([a.width, a.height, a.rotatedByMetadata, a.orientation]).toEqual([1200, 1600, true, 'portrait'])
    expect(a.ratio?.label).toBe('3:4')
    const plain = analyze(await solid(1600, 1200, 3, '#ffffff').jpeg().withMetadata({ orientation: 1 }).toBuffer())
    expect([plain.width, plain.height, plain.rotatedByMetadata]).toEqual([1600, 1200, false])
  })

  test('[AC-TOOL-001] HEIC (iPhone) header: primary image size, irot rotation and brand detection', () => {
    const a = analyze(heic(4032, 3024))
    expect([a.format, a.width, a.height, a.rotatedByMetadata, a.error]).toEqual(['heic', 4032, 3024, false, null])
    expect(a.ratio?.label).toBe('4:3')
    const rotated = analyze(heic(4032, 3024, 1))
    expect([rotated.width, rotated.height, rotated.rotatedByMetadata]).toEqual([3024, 4032, true])
    expect(sniffFormat(heic(10, 10))).toBe('heic')
  })

  test('[AC-TOOL-001] BMP, tiny, huge, square, panorama and very tall images', async () => {
    expect(readHeader(bmp(640, -480))).toMatchObject({ format: 'bmp', width: 640, height: 480 })
    const tiny = analyze(await solid(1, 1, 3, '#000000').png().toBuffer())
    expect([tiny.width, tiny.height, tiny.orientation, tiny.ratio?.label]).toEqual([1, 1, 'square', '1:1'])
    const huge = analyze(pngHeader(30000, 20000))
    expect([huge.width, huge.height, huge.megapixels, huge.ratio?.label, huge.orientation]).toEqual([30000, 20000, 600, '3:2', 'landscape'])
    expect(analyze(await solid(1000, 1000, 3, '#fff').jpeg().toBuffer()).orientation).toBe('square')
    const pano = analyze(await solid(4000, 1000, 3, '#fff').jpeg().toBuffer())
    expect([pano.orientation, pano.ratio?.label]).toEqual(['panorama', '4:1'])
    expect(analyze(await solid(1000, 2500, 3, '#fff').jpeg().toBuffer()).orientation).toBe('tall')
  })

  test('[AC-TOOL-001] aspect ratio labels, orientation thresholds and sizes', () => {
    expect(aspectRatio(1600, 1200).label).toBe('4:3')
    expect(aspectRatio(1920, 1080).label).toBe('16:9')
    expect(aspectRatio(1920, 1081)).toMatchObject({ label: '≈ 16:9', common: [16, 9] })
    expect(aspectRatio(2370, 1000)).toMatchObject({ label: '2,37:1', common: null })
    expect(aspectRatio(1000, 2370).label).toBe('1:2,37')
    expect(orientationOf(1005, 1000)).toBe('square')
    expect(orientationOf(1200, 1000)).toBe('landscape')
    expect(orientationOf(1000, 1200)).toBe('portrait')
    expect(formatBytes(999)).toBe('999 B')
    expect(formatBytes(250_000)).toBe('250 kB')
    expect(formatBytes(5 * MB)).toBe('5 MB')
    expect(formatBytes(12_345_678)).toBe('12,35 MB')
  })

  test('[AC-TOOL-001] empty, random, truncated and non-image files give a readable error instead of an exception', async () => {
    expect(analyze(new Uint8Array(0)).error).toBe('Plik jest pusty.')
    let seed = 42
    const random = new Uint8Array(4096).map(() => (seed = (seed * 1103515245 + 12345) % 2 ** 31) & 255)
    random[0] = 0x00
    const r = analyze(random, 'random.bin')
    expect(r.format).toBe('unknown')
    expect(r.error).toMatch(/nie jest obsługiwany plik graficzny/)
    const jpeg = await solid(800, 600, 3, '#ffffff').jpeg().toBuffer()
    const cut = analyze(jpeg.subarray(0, 30), 'cut.jpg')
    expect(cut.format).toBe('jpeg')
    expect(cut.error).toMatch(/uszkodzony lub niepełny/)
    expect(cut.width).toBeNull()
    const text = analyze(new TextEncoder().encode('<html>to nie jest zdjęcie</html>'))
    expect(text.error).not.toBeNull()
    const brokenPng = pngHeader(100, 100).slice(0, 20)
    expect(analyze(brokenPng).error).toMatch(/PNG/)
    // A corrupted file never gets platform results.
    expect(evaluateAll(cut, CHECKED_AT).every((p) => p.status === 'info' && p.checks.length === 0)).toBe(true)
  })
})

/** RGBA canvas filled with `bg`, with an optional opaque dark product rectangle. */
function canvas(w: number, h: number, bg: [number, number, number, number], product?: { x: number; y: number; w: number; h: number }) {
  const px = new Uint8ClampedArray(w * h * 4)
  for (let i = 0; i < w * h; i++) px.set(bg, i * 4)
  if (product) {
    for (let y = product.y; y < product.y + product.h; y++) for (let x = product.x; x < product.x + product.w; x++) px.set([40, 30, 20, 255], (y * w + x) * 4)
  }
  return px
}

test.describe('[AC-TOOL-002] white background and transparency estimate', () => {
  const center = { x: 30, y: 30, w: 40, h: 40 }

  test('[AC-TOOL-002] white, light grey, coloured and transparent backgrounds', () => {
    const white = pixelStats(canvas(100, 100, [255, 255, 255, 255], center), 100, 100)
    expect(white.border.verdict).toBe('white')
    expect(white.border.pureWhiteShare).toBe(1)
    expect(white.transparentShare).toBe(0)
    expect(white.border.sampled).toBe(100 * 100 - 96 * 96) // band of 2 px

    expect(pixelStats(canvas(100, 100, [240, 240, 240, 255], center), 100, 100).border.verdict).toBe('light')
    expect(pixelStats(canvas(100, 100, [250, 250, 250, 255], center), 100, 100).border).toMatchObject({ verdict: 'light', pureWhiteShare: 0 })
    expect(pixelStats(canvas(100, 100, [30, 120, 200, 255], center), 100, 100).border.verdict).toBe('not-white')

    const transparent = pixelStats(canvas(100, 100, [0, 0, 0, 0], center), 100, 100)
    expect(transparent.border.verdict).toBe('transparent')
    expect(transparent.transparentShare).toBeCloseTo(1 - (40 * 40) / (100 * 100), 6)
  })

  test('[AC-TOOL-002] a product touching the edge lowers the white share', () => {
    const touching = pixelStats(canvas(100, 100, [255, 255, 255, 255], { x: 0, y: 20, w: 50, h: 60 }), 100, 100)
    expect(touching.border.verdict).toBe('not-white')
    expect(touching.border.pureWhiteShare).toBeLessThan(0.98)
    // a 1-pixel image still samples itself
    expect(pixelStats(new Uint8ClampedArray([255, 255, 255, 255]), 1, 1).border).toMatchObject({ sampled: 1, verdict: 'white' })
  })

  test('[AC-TOOL-002] JPEG compression of pure white stays "pure white" (tolerance 1)', async () => {
    const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300"><rect width="400" height="300" fill="#fff"/><circle cx="200" cy="150" r="80" fill="#a33"/></svg>')
    const jpeg = await sharp(svg).flatten({ background: '#ffffff' }).jpeg({ quality: 85 }).toBuffer()
    const { data, info } = await sharp(jpeg).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
    expect(pixelStats(data, info.width, info.height).border.verdict).toBe('white')
    const grey = await sharp(svg).flatten({ background: '#ffffff' }).modulate({ brightness: 0.93 }).jpeg().toBuffer()
    const g = await sharp(grey).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
    expect(pixelStats(g.data, g.info.width, g.info.height).border.verdict).not.toBe('white')
  })
})

